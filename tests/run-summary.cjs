const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
let now = 0;
const context = vm.createContext({ performance: { now: () => now }, resetScoreSent() {} });
vm.runInContext(fs.readFileSync('assets/js/core/state.js', 'utf8') + '\nglobalThis.state = GameState;', context);
const state = context.state;
state.currentMissions = () => Array.from({length:5}, (_, i) => ({id:`q${i}`}));
state.startRun();
now = 61234;
assert.equal(state.elapsedTime(), 61234);
state.isPaused = true;
now += 10000;
assert.equal(state.elapsedTime(), 71234, 'Consultas e perguntas não interrompem o cronômetro');
state.recordAnswer({id:'q0',type:'choice'}, true, 5);
state.recordAnswer({id:'q0',type:'choice'}, true, 5);
assert.equal(state.getRunSummary().rooms[0].score, 5, 'Uma resposta não é registrada duas vezes');
state.finishRoomAttempt('failed');
state.roomRestarts.sala1 = 1;
state.startRoomAttempt();
state.recordAnswer({id:'q1',type:'matching'}, true, 4);
state.recordAnswer({id:'q2',type:'choice'}, false, 0);
state.score = 4;
state.finishRoomAttempt('cleared');
let summary = state.getRunSummary();
assert.equal(summary.rooms[0].correct, 1);
assert.equal(summary.rooms[0].answered, 2);
assert.equal(summary.rooms[0].score, 4);
assert.equal(summary.rooms[0].discarded[0].score, 5);
assert.equal(summary.restarts, 1);
state.stopClock();
now += 999999;
assert.equal(state.elapsedTime(), 71234, 'Tempo final permanece congelado');
state.resetFull();
assert.equal(state.elapsedTime(), 0);
assert.equal(state.totalRoomRestarts(), 0);
assert.equal(state.getRunSummary().rooms.length, 0);
console.log('OK: relógio contínuo, tentativas descartadas, acertos válidos, registro único e nova partida');
